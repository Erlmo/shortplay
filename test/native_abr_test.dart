import 'dart:convert';
import 'dart:io';

import 'package:flutter_test/flutter_test.dart';
import 'package:shortplay_playback_sdk/shortplay_playback_sdk.dart';

NativeAbrSnapshot _sample(Map<String, dynamic> s) => NativeAbrSnapshot(
      elapsedMilliseconds: s['elapsedMilliseconds'] as int,
      bufferSeconds: (s['bufferSeconds'] as num).toDouble(),
      predictedBandwidth: s['predictedBandwidth'] as int,
      bandwidthRecords: List<int>.from(s['bandwidthRecords'] as List),
      bufferRecords: (s['bufferRecords'] as List)
          .map((value) => (value as num).toDouble())
          .toList(),
      opened: s['opened'] as bool,
      enabled: s['enabled'] as bool,
      peakBandwidth: s['peakBandwidth'] as int,
      segmentMilliseconds: s['segmentMilliseconds'] as int,
      bufferState: s['bufferState'] as int,
    );

NativeAbrSnapshot _observation(int time,
        {double buffer = 0.1, int segment = 1000}) =>
    NativeAbrSnapshot(
      elapsedMilliseconds: time,
      bufferSeconds: buffer,
      predictedBandwidth: 100000,
      bandwidthRecords: const [100000],
      bufferRecords: const [0.1],
      segmentMilliseconds: segment,
    );

void main() {
  // Expectations are recorded from original ARM64 machine code under Unicorn,
  // not generated by a second implementation of this Dart selector.
  final fixture = jsonDecode(
          File('test/fixtures/native_abr_pid_vectors.json').readAsStringSync())
      as Map<String, dynamic>;
  final cases = fixture['cases'] as List;
  test('带宽调和平均及峰值合并与原始机器码40组向量一致', () {
    for (final raw in fixture['helpers'] as List) {
      final h = raw as Map<String, dynamic>;
      expect(nativeAbrHarmonicBandwidth(List<int>.from(h['records'] as List)),
          h['harmonic']);
      expect(
          nativeAbrUpdatedBandwidth(
              h['count'] as int, h['predicted'] as int, h['peak'] as int),
          h['updated']);
    }
  });
  for (var index = 0; index < cases.length; index++) {
    test('原生PID机器码状态序列$index：选档和四组计数逐次一致', () {
      final c = cases[index] as Map<String, dynamic>;
      final config = c['config'] as Map<String, dynamic>;
      final selector = NativeAbrPidSelector(
          config: NativeAbrPidConfig(
        targetBufferSeconds: (config['targetBufferSeconds'] as num).toDouble(),
        safeBufferRatio: (config['safeBufferRatio'] as num).toDouble(),
        kp: (config['kp'] as num).toDouble(),
        ki: (config['ki'] as num).toDouble(),
        kd: (config['kd'] as num).toDouble(),
        switchCount: config['switchCount'] as int,
        backoffEnabled: config['backoffEnabled'] as bool,
        switchLimit: config['switchLimit'] as int,
        downBufferMilliseconds: config['downBufferMilliseconds'] as int,
        maximumBandwidthFactor:
            (config['maximumBandwidthFactor'] as num).toDouble(),
      ));
      for (final raw in c['steps'] as List) {
        final step = raw as Map<String, dynamic>;
        final selected = selector.select(
            bitrates: List<int>.from(c['levels'] as List),
            current: step['current'] as int,
            sample: _sample(step['sample'] as Map<String, dynamic>));
        expect({
          'selected': selected,
          'upCount': selector.upCount,
          'downCount': selector.downCount,
          'backoff': selector.backoff,
          'switchCount': selector.switchCount,
        }, step['expected']);
      }
    });
  }

  test('低缓冲等待使用旧计数比较，非紧急时第5次才降档', () {
    final selector = NativeAbrPidSelector();
    for (var i = 0; i < 5; i++) {
      expect(
          selector.select(
              bitrates: [300000, 1200000],
              current: 1200000,
              sample: _observation(5000 + i * 500)),
          i == 4 ? 300000 : 1200000);
    }
  });
  test('缓冲超过分片长度时无需等待降档计数，边界相等仍等待', () {
    final selector = NativeAbrPidSelector();
    expect(
        selector.select(
            bitrates: [300000, 1200000],
            current: 1200000,
            sample: _observation(5000, buffer: 1)),
        1200000);
    expect(
        selector.select(
            bitrates: [300000, 1200000],
            current: 1200000,
            sample: _observation(5500, buffer: 1.001)),
        300000);
  });
  test('缺测和手动锁定不自动选档，重复快照不累加，切源重置计数', () {
    const low = QualityRendition('360p', 300000, 'whole-low-model');
    const high = QualityRendition('1080p', 1200000, 'whole-high-model');
    final policy = NativeAbrQualityPolicy();
    QualityRendition<String> choose(String source, NativeAbrSnapshot? sample,
            {bool manual = false}) =>
        policy.recommend(
            sourceId: source,
            items: [low, high],
            current: high,
            sample: sample,
            manual: manual);
    expect(choose('a', null), same(high));
    for (var i = 0; i < 4; i++) {
      expect(choose('a', _observation(5000 + i * 500)), same(high));
    }
    expect(policy.selector.downCount, 4);
    expect(choose('a', _observation(6500)), same(high));
    expect(policy.selector.downCount, 4);
    expect(choose('a', _observation(7000)), same(low));
    expect(choose('b', _observation(7500)), same(high));
    expect(policy.selector.downCount, 1);
    expect(choose('b', _observation(8000), manual: true), same(high));
    expect(policy.selector.downCount, 0);
  });

  test('未知缓冲、无设备观测和源头4秒内维持当前清晰度', () {
    final selector = NativeAbrPidSelector();
    expect(
        selector.select(
            bitrates: [300000, 1200000],
            current: 1200000,
            sample: _observation(3999, buffer: 1.1, segment: 0)),
        1200000);
    expect(
        selector.select(
            bitrates: [300000, 1200000],
            current: 1200000,
            sample: _observation(5000, buffer: double.nan)),
        1200000);
    expect(selector.switchCount, 0);
  });
}
