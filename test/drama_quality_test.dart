import 'dart:convert';
import 'dart:io';

import 'package:flutter_test/flutter_test.dart';
import 'package:shortplay/models/fq_video.dart';
import 'package:shortplay/services/api_client.dart';
import 'package:shortplay/services/theater_video_preload_manager.dart';
import 'package:shortplay_playback_sdk/shortplay_playback_sdk.dart';

class _Models extends ApiClient {
  _Models(this.definitions);
  final List<String> definitions;
  int calls = 0;
  @override
  Future<List<FqVideoItem>> fetchFqVideoModel(String videoId) async {
    calls++;
    return [
      for (final definition in definitions)
        FqVideoItem(
          url: 'https://cdn.example/$videoId-$definition.mp4',
          definition: definition,
          width: 0,
          height: 0,
          bitrate: 100,
          codec: 'hevc',
          spadeA: '',
          kid: '',
          isEncrypted: false,
        )
    ];
  }
}

void main() {
  test('真实红果Java入口100组参考向量：播放与预加载顺序一致', () {
    // Generated by compiling the original REA a/c method bodies, with external
    // strategy inputs stubbed. Expectations do not use the Dart implementation.
    final cases = jsonDecode(
        File('test/fixtures/hongguo_drama_quality_vectors.json')
            .readAsStringSync()) as List;
    for (final raw in cases) {
      final value = raw as Map<String, dynamic>;
      final supported = List<String>.from(value['supported'] as List);
      final allowed = List<String>.from(value['allowed'] as List);
      expect(
          DramaQualitySelector.playback(
            supported: supported,
            allowed: allowed,
            offline: value['offline'] as String?,
            manual: value['manual'] as String?,
            cached: value['cached'] as String?,
            strategy: value['strategy'] as String?,
          ),
          value['playback']);
      expect(
          DramaQualitySelector.preload(
            supported: supported,
            allowed: allowed,
            manual: value['manual'] as String?,
            cached: value['cached'] as String?,
            strategy: value['strategy'] as String?,
          ),
          value['preload']);
    }
  });

  test('正式播放无720时按模型原序，预加载按宿主允许顺序', () async {
    final api = _Models(['1080p', '360p']);
    addTearDown(api.dispose);
    final player = TheaterVideoPreloadManager(
        apiClient: api, configureNetwork: (_) async {});
    expect(await player.resolvePlayUrl('one', episodeIndex: 0),
        endsWith('one-1080p.mp4'));
    expect(
        await player.resolvePlayUrl('two', episodeIndex: 1, forPreload: true),
        endsWith('two-360p.mp4'));
    // An already prepared source retains ownership; foreground does not change
    // its rendition underneath an existing first-frame/cache preparation.
    expect(await player.resolvePlayUrl('two', episodeIndex: 1),
        endsWith('two-360p.mp4'));
    expect(api.calls, 2);
  });

  test('正式路径优先最后一个正缓存档，手选覆盖缓存且复用原模型', () async {
    final api = _Models(['1080p', '480p', '360p']);
    addTearDown(api.dispose);
    final configured = <String>[];
    final player = TheaterVideoPreloadManager(
      apiClient: api,
      hasCachedMedia: (_) => true,
      configureNetwork: (item) async => configured.add(item.url),
    );
    expect(await player.resolvePlayUrl('one', episodeIndex: 0),
        endsWith('one-480p.mp4'));
    player.setPreferredDefinition('1080p');
    expect(await player.resolvePlayUrl('one', episodeIndex: 0),
        endsWith('one-1080p.mp4'));
    expect(api.calls, 1);
    expect(configured, [
      'https://cdn.example/one-480p.mp4',
      'https://cdn.example/one-1080p.mp4'
    ]);
  });

  test('未命中缓存时正式播放维持720，缓存探测失败也可起播', () async {
    final api = _Models(['1080p', '360p', '720p']);
    addTearDown(api.dispose);
    final player = TheaterVideoPreloadManager(
        apiClient: api,
        hasCachedMedia: (_) =>
            throw const FileSystemException('synthetic miss'),
        configureNetwork: (_) async {});
    expect(await player.resolvePlayUrl('one', episodeIndex: 0),
        endsWith('one-720p.mp4'));
  });

  test('真实缓存探测验证字节，不把元数据、临时块或损坏块当命中', () {
    final directory = Directory.systemTemp.createTempSync('drama-quality-');
    addTearDown(() => directory.deleteSync(recursive: true));
    final cache = MediaCacheStore(directory);
    const url = 'https://cdn.example/synthetic.mp4';
    cache.write(url, 0, List.filled(MediaCacheStore.blockSize, 7),
        totalLength: MediaCacheStore.blockSize);
    expect(cache.hasVerifiedMedia(url), true);
    final block =
        File('${directory.path}/${MediaCacheStore.identity(url)}/blocks/0.blk');
    final bytes = block.readAsBytesSync();
    bytes[bytes.length - 1] ^= 1;
    block.writeAsBytesSync(bytes);
    expect(cache.hasVerifiedMedia(url), false);
    expect(cache.metadata(url), isNotNull);
    File('${block.path}.tmp').writeAsBytesSync(bytes);
    expect(cache.hasVerifiedMedia(url), false);
  });
}
